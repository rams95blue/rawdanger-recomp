#!/usr/bin/env python3
"""
rd_voicepack.py - build the Japanese voice pack used by voice_language = jp.

  rd_voicepack.py --us work/us --jp work/jp --out work/us/voice_jp PATH [PATH ...]
  rd_voicepack.py --us work/us --jp work/jp --out work/us/voice_jp --from-candidates work/reports/voice_candidates.json

For every disc path given (e.g. /DATA/VOICE.BIN) it copies the JP file into
voice_jp/ and writes voice_map.txt with:

  file <path> = <path>          always - catches name-based opens (sceCdSearchFile / cdrom0:)
  lba  <US LBA> <US sectors> = <path>
                                only if the JP file fits in the US file's sector span -
                                catches raw sector reads through a hard-coded TOC

Nothing on either disc is modified; the swap happens at runtime in rd_game.cpp,
so voice language can be flipped in rawdanger.ini without rebuilding.

IMPORTANT: a file-level swap only works when the US executable understands the
JP container's internal index. The US undub notes say the audio archive was
EXPANDED with JP-only entries (NPCs speaking the protagonist's name) and six
English-only clips were muted - that needs entry-level work in a later phase
(see docs/VOICE_SWAP.md). Start with whole-file swaps, test, then refine.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys

SECTOR = 2048


def load_manifest(root):
    p = os.path.join(root, "_rd_manifest.json")
    if not os.path.exists(p):
        sys.exit(f"{p} missing - extract with rd_iso.py first")
    with open(p, encoding="utf-8") as f:
        m = json.load(f)
    return {fi["path"].upper(): fi for fi in m["files"]}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--us", required=True)
    ap.add_argument("--jp", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--from-candidates")
    ap.add_argument("--no-lba", action="store_true", help="only write file routes")
    ap.add_argument("paths", nargs="*")
    a = ap.parse_args(argv)

    us, jp = load_manifest(a.us), load_manifest(a.jp)
    paths = list(a.paths)
    if a.from_candidates:
        with open(a.from_candidates, encoding="utf-8") as f:
            paths += [c["path"] for c in json.load(f)]
    if not paths:
        sys.exit("no paths given")
    os.makedirs(a.out, exist_ok=True)
    lines = ["# Generated by rd_voicepack.py - JP voice routes for rd_game.cpp",
             "# file <disc path> = <file in this folder>",
             "# lba <US LBA> <US sectors> = <file in this folder>", ""]
    for p in paths:
        key = "/" + p.strip().lstrip("/\\").replace("\\", "/").upper()
        u, j = us.get(key), jp.get(key)
        if not j:
            print(f"  skip {key}: not on JP disc")
            continue
        rel = j["path"].lstrip("/")
        src = os.path.join(a.jp, rel.replace("/", os.sep))
        dst = os.path.join(a.out, rel.replace("/", os.sep))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        lines.append(f"file {j['path']} = {rel}")
        msg = f"  {key}: JP {j['size']:,} B"
        if u:
            us_sectors = (u["size"] + SECTOR - 1) // SECTOR
            jp_sectors = (j["size"] + SECTOR - 1) // SECTOR
            if a.no_lba:
                pass
            elif jp_sectors <= us_sectors:
                lines.append(f"lba {u['lba']} {us_sectors} = {rel}")
                msg += f" fits US slot ({jp_sectors}/{us_sectors} sectors) -> file+lba"
            else:
                msg += (f" is {jp_sectors - us_sectors} sectors LARGER than the US slot -> file route only; "
                        "raw-LBA reads would need an entry-level redirect")
        else:
            msg += " (JP-only file) -> file route only"
        print(msg)
    with open(os.path.join(a.out, "voice_map.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {os.path.join(a.out, 'voice_map.txt')}")
    print("Set  [audio] voice_language = jp  in rawdanger.ini to use it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
